-- マスターの内容の指紋（DEC-PLT-053）。
--
-- マスター WAV のファイル全体の SHA-256 を、小文字の16進（64字）で持つ。 パスや
-- 更新時刻ではなく中身の指紋なので、同じ中身が別の場所にあれば同じ値になり、同じ場所で
-- 中身が変われば別の値になる。 ジョブが読んだ入力の印と、試唱の素材の鍵が使う。
--
-- **NULL は「まだ計算していない」であって、「無い」ではない。** SQL はファイルを読めない
-- ので、この移行では埋めない。 既存のテイクは NULL のまま残り、最初に要ったときに
-- アプリがファイルから計算して書く（書いたあとは変えない）。 新しいテイクは、確定の
-- 直後に書く。 確定と同じトランザクションではない——ファイルの中身は確定のあとで読む。
ALTER TABLE takes ADD COLUMN master_sha256 TEXT
  CHECK (master_sha256 IS NULL OR length(master_sha256) = 64);
