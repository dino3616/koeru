/*
 * 入力レベルにまつわる定数。
 *
 * # 良し悪しの区分を持たない
 *
 * 以前は「小さすぎる」「ちょうどよい」の閾値をここに置いていた。
 * `DEC-REC-008` が観測をフラットに報告するだけと決めたのに、
 * ライブのメーターだけが判定していた（`Q-REC-004`）。区分ごと外した。
 *
 * 残っているのは、割れているかどうかだけ。 これは判定ではなく、
 * 起きたことの記録（`TR-REC-16` の計測）。
 */

/**
 * クリップとみなす下限。
 *
 * 1.0 ではなく 0.999。理由と正本は Rust 側の
 * `koeru_core::analysis::CLIP_THRESHOLD`。ずれは
 * `koeru-app` の `画面のクリップ閾値がrustと一致する` が落とす。
 */
export const CLIP_THRESHOLD = 0.999;

/**
 * 入力が届いているかを確かめる長さ（ミリ秒）。
 *
 * マイクを開いたあと、これだけ聴いてから収録へ進む。 `Session` は
 * 開いただけでは「届いているか未確認」で、`probe_input` が通るまで
 * `start_take` を受け付けない（`REQ-REC-106`）。
 *
 * 0.4 秒。 短くすると立ち上がりの無音を掴んで「届いていない」になり、
 * 長くすると押してから録りはじめるまでが目に見えて遅くなる。
 */
export const PROBE_MS = 400;
